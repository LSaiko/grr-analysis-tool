def fig_to_image(fig: plt.Figure, w_in: float, h_in: float) -> Image:
    """
    Convert a matplotlib Figure to a ReportLab Image flowable.

    Args:
        fig:  Matplotlib figure (will be closed after conversion).
        w_in: Rendered width in inches.
        h_in: Rendered height in inches.

    Returns:
        A ReportLab ``Image`` flowable containing the figure as PNG.

    Example:
        >>> fig, ax = plt.subplots()
        >>> ax.plot([1, 2, 3], [4, 5, 6])
        >>> img = fig_to_image(fig, w_in=6.5, h_in=3.0)
    """
    buf = BytesIO()
    fig.savefig(buf, format="png", dpi=150, bbox_inches="tight",
                facecolor=fig.get_facecolor())
    buf.seek(0)
    img = Image(buf, width=w_in * inch, height=h_in * inch)
    plt.close(fig)
    return img


def embed_chart(fig: plt.Figure, w_in: float = 6.8, h_in: float = 3.0) -> List:
    """
    Wrap ``fig_to_image`` with standard spacing for embedding in a story.

    Args:
        fig:  Matplotlib figure.
        w_in: Chart width in inches (default 6.8 — fits letter with margins).
        h_in: Chart height in inches (default 3.0).

    Returns:
        List of [Image, Spacer] flowables.

    Example:
        >>> story += embed_chart(my_fig, w_in=6.8, h_in=2.8)
    """
    return [fig_to_image(fig, w_in, h_in), Spacer(1, 0.08 * inch)]


# ---------------------------------------------------------------------------
# Palette helper for matplotlib charts
# ---------------------------------------------------------------------------

def palette_style(ax: plt.Axes) -> None:
    """
    Apply the msa_toolkit house style to a matplotlib Axes.

    Removes top/right spines, adds light y-grid, sets axis below grid.

    Args:
        ax: Matplotlib Axes to style.

    Example:
        >>> fig, ax = plt.subplots()
        >>> palette_style(ax)
    """
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.yaxis.grid(True, linestyle=":", alpha=0.5, zorder=0)
    ax.set_axisbelow(True)
