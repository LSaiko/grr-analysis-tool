# ---------------------------------------------------------------------------
# Paragraph style factory
# ---------------------------------------------------------------------------

def para_style(name: str, **kw) -> ParagraphStyle:
    """
    Create a named ParagraphStyle with sensible defaults.

    Args:
        name: Unique style name (must be distinct within a document).
        **kw:  Any ParagraphStyle keyword argument overrides.

    Returns:
        A configured ``ParagraphStyle`` instance.

    Example:
        >>> s = para_style("MyTitle", fontSize=16, fontName="Helvetica-Bold")
    """
    defaults = dict(fontName="Helvetica", fontSize=9, spaceAfter=4, leading=13)
    defaults.update(kw)
    return ParagraphStyle(name, **defaults)


# ---------------------------------------------------------------------------
# Common flowables
# ---------------------------------------------------------------------------

def hr_heavy() -> HRFlowable:
    """Return a 1.5pt dark-blue horizontal rule (use after title block)."""
    return HRFlowable(width="100%", thickness=1.5, color=colors.HexColor(NAVY))


def hr_light() -> HRFlowable:
    """Return a 0.5pt light-grey horizontal rule (use between sections)."""
    return HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#D0D3D4"))


