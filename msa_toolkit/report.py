"""
msa_toolkit.report
==================
Shared ReportLab Platypus building blocks used by anova, capability,
and control_charts modules.  All helpers return Platypus flowable
objects or lists thereof so callers can append them into a story list
and call ``SimpleDocTemplate.build(story)``.

This module does NOT modify or duplicate grr_tool.py.  Existing PDF
output in grr_tool.py is unchanged; this module is consumed only by
the new msa_toolkit modules.

Regulatory footer text per 21 CFR 820.72 is embedded in every
``make_footer`` call.
"""

