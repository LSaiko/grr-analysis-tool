def make_doc(
    output_path: Path,
    title: str = "MSA Report",
    author: str = "msa_toolkit",
) -> SimpleDocTemplate:
    """
    Create a letter-size ``SimpleDocTemplate`` with standard margins.

    Args:
        output_path: Destination PDF path.
        title:       PDF document title metadata.
        author:      PDF document author metadata.

    Returns:
        A ``SimpleDocTemplate`` ready for ``.build(story)``.
    """
    return SimpleDocTemplate(
        str(output_path),
        pagesize=letter,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
        topMargin=0.65 * inch,
        bottomMargin=0.80 * inch,
        title=title,
        author=author,
        subject="MSA Report — msa_toolkit",
    )


# ---------------------------------------------------------------------------
# Header block
# ---------------------------------------------------------------------------

def make_header(
    title: str,
    metadata: Dict[str, str],
    subtitle: str = "",
) -> List:
    """
    Build a standard report header block (title + metadata table + HR).

    Args:
        title:    Main report title string.
        metadata: Ordered dict of ``{label: value}`` rows shown below the
                  title (e.g. ``{"Equipment": "CMM SN-001", "Date": "..."}``.
        subtitle: Optional single-line subtitle below the main title.

    Returns:
        List of Platypus flowables to append to a story.

    Example:
        >>> story += make_header("Capability Report", {"LSL": "9.95", "USL": "10.05"})
    """
    s_title = para_style("rpt_title", fontSize=16,
                         fontName="Helvetica-Bold",
                         textColor=colors.HexColor(NAVY),
                         alignment=1, spaceAfter=3)
    s_sub   = para_style("rpt_sub", fontSize=8.5,
                         textColor=colors.HexColor("#555555"),
                         alignment=1, spaceAfter=10)
    s_meta_k = para_style("rpt_meta_k", fontSize=8.5,
                          fontName="Helvetica-Bold",
                          textColor=colors.HexColor(NAVY))
    s_meta_v = para_style("rpt_meta_v", fontSize=8.5)

    story: List = [Paragraph(title, s_title)]
    if subtitle:
        story.append(Paragraph(subtitle, s_sub))

    rows = [[Paragraph(k, s_meta_k), Paragraph(v, s_meta_v)]
            for k, v in metadata.items()]
    if rows:
        tbl = Table(rows, colWidths=[1.9 * inch, 5.1 * inch])
        tbl.setStyle(TableStyle([
            ("FONTSIZE",       (0, 0), (-1, -1), 8.5),
            ("BOTTOMPADDING",  (0, 0), (-1, -1), 3),
            ("TOPPADDING",     (0, 0), (-1, -1), 2),
        ]))
        story += [tbl, Spacer(1, 0.08 * inch)]

    story += [hr_heavy(), Spacer(1, 0.10 * inch)]
    return story


# ---------------------------------------------------------------------------
# Footer block
# ---------------------------------------------------------------------------

def make_footer(extra_note: str = "") -> List:
    """
    Build a standard regulatory footer block.

    Args:
        extra_note: Optional additional sentence appended after the
                    standard 21 CFR 820.72 footer text.

    Returns:
        List of Platypus flowables.

    Example:
        >>> story += make_footer("Study conducted under ISO 13485 QMS.")
    """
    s_footer = para_style(
        "rpt_footer",
        fontSize=6.5,
        fontName="Helvetica-Oblique",
        textColor=colors.HexColor("#888888"),
        spaceBefore=4,
    )
    text = REG_FOOTER
    if extra_note:
        text += " " + extra_note
    return [hr_light(), Spacer(1, 4), Paragraph(text, s_footer)]


# ---------------------------------------------------------------------------
# Section heading
# ---------------------------------------------------------------------------

def section_heading(text: str) -> Paragraph:
    """
    Return a bold navy section heading paragraph.

    Args:
        text: Heading text.

    Returns:
        A ``Paragraph`` flowable.

    Example:
        >>> story.append(section_heading("Variance Components"))
    """
    s = para_style(
        f"rpt_sect_{text[:8].replace(' ', '_')}",
        fontSize=10.5,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor(NAVY),
        spaceBefore=8,
        spaceAfter=4,
    )
    return Paragraph(text, s)


