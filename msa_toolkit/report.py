def metrics_table(
    rows: List[List[str]],
    col_widths: Sequence[float],
    highlight_rows: Optional[List[Tuple[int, str]]] = None,
    header_color: str = NAVY,
) -> Table:
    """
    Build a styled data table with a dark header row.

    Args:
        rows:           List of row lists (first row = header).
        col_widths:     Column widths in inches.
        highlight_rows: Optional list of ``(row_index, hex_color)`` for
                        background-highlighted body rows (1-based index,
                        header is row 0).
        header_color:   Hex color for the header background.

    Returns:
        A styled ``Table`` flowable.

    Example:
        >>> tbl = metrics_table(
        ...     [["Component", "Value", "%TV"],
        ...      ["EV", "0.00872", "10.1%"]],
        ...     col_widths=[2.5, 1.2, 1.0],
        ... )
    """
    cw = [w * inch for w in col_widths]
    tbl = Table(rows, colWidths=cw, repeatRows=1)

    style_cmds = [
        ("BACKGROUND",     (0, 0),  (-1, 0),  colors.HexColor(header_color)),
        ("TEXTCOLOR",      (0, 0),  (-1, 0),  colors.white),
        ("FONTNAME",       (0, 0),  (-1, 0),  "Helvetica-Bold"),
        ("FONTSIZE",       (0, 0),  (-1, -1), 8.5),
        ("ROWBACKGROUNDS", (0, 1),  (-1, -1), [colors.HexColor("#F4F6F8"), colors.white]),
        ("GRID",           (0, 0),  (-1, -1), 0.4, colors.HexColor("#D0D3D4")),
        ("TOPPADDING",     (0, 0),  (-1, -1), 5),
        ("BOTTOMPADDING",  (0, 0),  (-1, -1), 5),
        ("LEFTPADDING",    (0, 0),  (-1, -1), 7),
        ("RIGHTPADDING",   (0, 0),  (-1, -1), 7),
        ("ALIGN",          (1, 0),  (-1, -1), "CENTER"),
        ("ALIGN",          (0, 0),  (0, -1),  "LEFT"),
    ]

    if highlight_rows:
        for row_idx, hex_color in highlight_rows:
            style_cmds += [
                ("BACKGROUND", (0, row_idx), (-1, row_idx), colors.HexColor(hex_color)),
                ("FONTNAME",   (0, row_idx), (-1, row_idx), "Helvetica-Bold"),
            ]

    tbl.setStyle(TableStyle(style_cmds))
    return tbl


